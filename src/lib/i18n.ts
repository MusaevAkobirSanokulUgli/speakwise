/**
 * Retrieve a translated string.
 * Falls back to English if the key is missing in the requested language.
 */
export function t(lang: string, category: string, key: string): string {
  const safeLang = (["en", "uz", "ru", "ko"].includes(lang) ? lang : "en") as Lang;
  const value =
    translations[safeLang]?.[category]?.[key] ??
    translations["en"]?.[category]?.[key] ??
    key;
  return value;
}
